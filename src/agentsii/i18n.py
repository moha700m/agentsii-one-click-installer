LANGS = {"en": EN, "ar": AR}


class Tr:
    def __init__(self, lang: str = "en"):
        self.lang = lang

    def __call__(self, key: str, **kw) -> str:
        s = LANGS[self.lang].get(key) or EN.get(key) or key
        return s.format(**kw) if kw else s

    @property
    def rtl(self) -> bool:
        return self.lang == "ar"
